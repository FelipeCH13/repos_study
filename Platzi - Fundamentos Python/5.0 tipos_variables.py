# Tipos de variables en Python

# Texto: string
comillasSimples = 'Hola Mundo'
comillasDobles = "Hola Mundo"
comillasTriples = '''Hola Mundo'''

print(comillasSimples)
print(comillasDobles)
print(comillasTriples)

# Números enteros: int
numeroEntero = 42
print(numeroEntero)

# Números decimales: float
numeroDecimal = 3.14
print(numeroDecimal)

# Listas: list
# Una lista es una colección ordenada y mutable de elementos, que pueden ser de diferentes tipos
miLista = [1, 2, 3, "Cuatro", "Cinco"]
print(miLista)

# Tuplas: tuple
# Una tupla es similar a una lista, pero es inmutable, lo que significa que no se puede modificar después de su creación
miTupla = (1, 2, 3, "Cuatro", "Cinco")
print(miTupla)

# Diccionarios: dict
# Un diccionario es una colección de pares clave-valor
miDiccionario = {"nombre": "Juan", "edad": 30, "ciudad": "Madrid"}
print(miDiccionario)

# Conjuntos: set
# Un conjunto es una colección no ordenada de elementos únicos
miConjunto = {1, 2, 3, "Cuatro", "Cinco"}
print(miConjunto)

# Booleanos: bool
# Un booleano es un tipo de dato que solo puede tener dos valores: True o False
esVerdadero = True
esFalso = False
print(esVerdadero)
print(esFalso)